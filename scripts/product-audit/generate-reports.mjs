inventory.push(`Generated from the current source tree at HEAD ${process.env.HEAD_SHA ?? 'unknown'}. This file is machine-generated by \`work/generate-reports.mjs\` and must be re-run after any route/view change.`);
inventory.push('');
inventory.push('## Counts');
inventory.push('');
inventory.push('| Metric | Value |');
inventory.push('| --- | ---: |');
inventory.push(`| TOTAL_MP_ROUTES | ${mpRoutes.totalRoutes} |`);
inventory.push(`| TOTAL_MP_UNIQUE_VIEWS | ${mpRoutes.totalUniqueViews} |`);
inventory.push(`| MP_VIEW_FILES | ${mpViews.length} |`);
inventory.push(`| TOTAL_ADMIN_ROUTES | ${adminRoutes.totalRoutes} |`);
inventory.push(`| ADMIN_VIEW_FILES | ${adminViews.length} |`);
inventory.push(`| TOTAL_ADMIN_RESOURCES | ${adminRoutes.menu.length} |`);
inventory.push(`| TOTAL_API_ENDPOINTS | ${apiEndpoints.total} |`);
inventory.push(`| TOTAL_DB_MODELS | ${dbModels.models.length} |`);
inventory.push(`| TOTAL_DB_ENUMS | ${dbModels.enums.length} |`);
inventory.push(`| TOTAL_CONTROLS (static) | ${controlManifest.total} |`);
inventory.push('');
inventory.push('## Tab routes');
inventory.push('');
inventory.push(mpRoutes.tabRoutes.map((r) => `- \`${r}\``).join('\n'));
inventory.push('');
inventory.push('## Alias groups (same component, multiple paths)');
inventory.push('');
inventory.push('| Component | Paths | Count |');
inventory.push('| --- | --- | ---: |');
for (const [comp, paths] of Object.entries(viewRoutes)) {
  if (paths.length > 1) inventory.push(`| ${comp} | ${paths.map((p) => `\`${p}\``).join('<br>')} | ${paths.length} |`);
}
inventory.push('');
inventory.push('## MP routes');
inventory.push('');
inventory.push('| Path | Component | Tab | AliasGroup |');
inventory.push('| --- | --- | --- | ---: |');
for (const r of mpRoutes.routes) {
  inventory.push(`| \`${r.path}\` | ${r.component ?? `(redirect -> ${r.redirect})`} | ${r.tabRoute ? 'yes' : ''} | ${r.aliasCount} |`);
}
inventory.push('');
inventory.push('## Admin routes / resources');
inventory.push('');
inventory.push('| Path | Component | Resource | Group | Title |');
inventory.push('| --- | --- | --- | --- | --- |');
for (const r of adminRoutes.routes) {
  inventory.push(`| \`${r.path}\` | ${r.component ?? `(redirect -> ${r.redirect})`} | ${r.resource ?? ''} | ${r.group ?? ''} | ${r.title ?? ''} |`);
}
inventory.push('');
inventory.push('## DB models');
inventory.push('');
inventory.push(dbModels.models.map((m) => `- ${m.name}`).join('\n'));
inventory.push('');
write('docs/product-audit/PRODUCT_INVENTORY.md', inventory.join('\n'));

// ---------- PAGE_AUDIT_MATRIX.md ----------
const pageMatrix = [];
pageMatrix.push('# PAGE AUDIT MATRIX');
pageMatrix.push('');
pageMatrix.push('One row per unique MP view and per admin resource. `Audit file` links the per-page audit document.');
pageMatrix.push('');
pageMatrix.push('| # | Surface | View | Routes | Controls | API reads | API writes | Audit file | Status |');
pageMatrix.push('| ---: | --- | --- | ---: | ---: | ---: | ---: | --- | --- |');
let i = 0;
for (const v of mpViews) {
  i += 1;
  const name = v.replace(/\.vue$/, '');
  const usage = apiUsage(v, 'apps/mp/src/views');
  const controls = (viewControls[v] ?? []).length;
  const routes = (viewRoutes[name] ?? []).map((p) => `\`${p}\``).join('<br>') || '(none)';
  pageMatrix.push(`| ${i} | mp | ${name} | ${routes} | ${controls} | ${usage.reads.length} | ${usage.writes.length} | [${name}.md](./pages/mp/${name}.md) | PENDING |`);
}
for (const item of adminRoutes.menu) {
  i += 1;
  const comp = adminRoutes.routes.find((r) => r.path === item.path)?.component ?? '(none)';
  pageMatrix.push(`| ${i} | admin | ${item.resource} | \`${item.path}\` | ${(adminViewControls[comp] ?? []).length} | - | - | [${item.resource}.md](./pages/admin/${item.resource}.md) | PENDING |`);
}
pageMatrix.push('');
write('docs/product-audit/PAGE_AUDIT_MATRIX.md', pageMatrix.join('\n'));

// ---------- CONTROL_AUDIT_MATRIX.md ----------
const controlMatrix = [];
controlMatrix.push('# CONTROL AUDIT MATRIX');
