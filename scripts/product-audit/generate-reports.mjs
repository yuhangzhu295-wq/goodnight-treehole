/* global process, console */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const j = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const write = (p, s) => {
  fs.mkdirSync(path.dirname(path.join(ROOT, p)), { recursive: true });
  fs.writeFileSync(path.join(ROOT, p), s);
};

const mpRoutes = j('artifacts/product-audit/mp-routes.json');
const adminRoutes = j('artifacts/product-audit/admin-routes.json');
const apiEndpoints = j('artifacts/product-audit/api-endpoints.json');
const dbModels = j('artifacts/product-audit/db-models.json');
const controlManifest = j('artifacts/product-audit/control-manifest.json');
const fakeMarkers = j('artifacts/product-audit/fake-markers.json');

// ---------- view -> routes / controls ----------
const viewRoutes = {};
for (const r of mpRoutes.routes) {
  if (!r.component) continue;
  (viewRoutes[r.component] ??= []).push(r.path);
}
const viewControls = {};
for (const c of controlManifest.controls) {
  if (c.surface !== 'mp') continue;
  (viewControls[c.view] ??= []).push(c);
}
const adminViewControls = {};
for (const c of controlManifest.controls) {
  if (c.surface !== 'admin') continue;
  (adminViewControls[c.view] ??= []).push(c);
}

// `api.get<{ item: X }>('/api/v1/tonight')` puts a generic argument list between the
// method and the call parenthesis, so the generic block has to be optional here.
const apiCallRe = /(?:api\.(get|post|patch|put|delete)(?:<[^<>]*(?:<[^<>]*>[^<>]*)*>)?|fetch)\s*\(\s*[`'"]\/api\/([^`'"?]*)/g;
function apiUsage(viewFile, dir) {
  const src = read(path.join(dir, viewFile));
  const reads = new Set();
  const writes = new Set();
  let m;
  const re = new RegExp(apiCallRe.source, 'g');
  while ((m = re.exec(src))) {
    const method = m[1] ? m[1].toUpperCase() : 'GET';
    const target = '/api/' + m[2].replace(/\$\{[^}]*\}/g, ':param');
    if (method === 'GET') reads.add(target);
    else writes.add(`${method} ${target}`);
  }
  return { reads: [...reads].sort(), writes: [...writes].sort() };
}

const mpViews = fs.readdirSync(path.join(ROOT, 'apps/mp/src/views')).filter((f) => f.endsWith('.vue'));
const adminViews = fs.readdirSync(path.join(ROOT, 'apps/admin/src/views')).filter((f) => f.endsWith('.vue'));

