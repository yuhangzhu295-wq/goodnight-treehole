write('docs/product-audit/CONTROL_AUDIT_MATRIX.md', controlMatrix.join('\n'));

// ---------- per-page skeletons ----------
const SECTIONS = ['PURPOSE','USER_JOB','ENTRY','EXIT','ROUTES','STATES','CONTROLS','API_READS','API_WRITES','DB_ENTITIES','ADMIN_VISIBILITY','AI_USAGE','PRIVACY','ERROR_STATES','EMPTY_STATES','NATIVE_RISKS','ISSUES','FINAL_STATUS'];
for (const v of mpViews) {
  const name = v.replace(/\.vue$/, '');
  const usage = apiUsage(v, 'apps/mp/src/views');
  const controls = viewControls[v] ?? [];
  const lines = [`# ${name}`, '', `Source: \`apps/mp/src/views/${v}\``, '', `Routes: ${(viewRoutes[name] ?? []).map((p) => `\`${p}\``).join(', ') || '(none)'}`, ''];
  for (const s of SECTIONS) lines.push(`## ${s}`, '', 'TBD', '');
  lines.push('### Static evidence', '');
  lines.push(`- Controls discovered: ${controls.length}`);
  lines.push(`- API reads (static): ${usage.reads.map((x) => `\`${x}\``).join(', ') || '(none)'}`);
  lines.push(`- API writes (static): ${usage.writes.map((x) => `\`${x}\``).join(', ') || '(none)'}`);
  lines.push(`- Candidate fake markers: ${(fakeMarkers.mp[v] ?? []).length}`);
  lines.push('');
  write(`docs/product-audit/pages/mp/${name}.md`, lines.join('\n'));
}
for (const item of adminRoutes.menu) {
  const comp = adminRoutes.routes.find((r) => r.path === item.path)?.component ?? '(none)';
  const controls = adminViewControls[comp] ?? [];
  const lines = [`# admin: ${item.resource} (${item.label})`, '', `Route: \`${item.path}\`  `, `Component: \`apps/admin/src/views/${comp}\``, `Group: ${item.group}`, ''];
  for (const s of SECTIONS) lines.push(`## ${s}`, '', 'TBD', '');
  lines.push('### Static evidence', '');
  lines.push(`- Controls discovered in component: ${controls.length}`);
  lines.push('');
  write(`docs/product-audit/pages/admin/${item.resource}.md`, lines.join('\n'));
}

