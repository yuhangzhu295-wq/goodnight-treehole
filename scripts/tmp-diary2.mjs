import { readFileSync } from 'node:fs';
import { PrismaClient } from '@prisma/client';
import crypto from 'node:crypto';
const env = readFileSync('.env', 'utf8');
const url = env.match(/^DATABASE_URL="?([^"\n]+)"?$/m)[1];
const p = new PrismaClient({ datasources: { db: { url } } });
const APP = 'user_anon_4c115912';
await p.user.upsert({ where: { id: APP }, create: { id: APP, openid: 'o_'+APP, anonymousCode: 'a_'+APP, nickname: 'n_'+APP }, update: {} });
const secret = crypto.randomBytes(32).toString('base64url');
const s = await p.anonymousSession.create({ data: { userId: APP, secretHash: crypto.createHash('sha256').update(secret).digest('hex'), expiresAt: new Date(Date.now()+86400000) } });
const cred = s.id + '.' + secret;
const r = await fetch('http://127.0.0.1:3000/api/v1/diaries', { headers: { 'x-goodnight-user-id': cred } });
const b = await r.json();
console.log('status', r.status, 'count', (b.items||[]).length);
console.log(JSON.stringify((b.items||[]).map(x=>({id:x.id,hasLetter:x.hasLetter,letterId:x.letterId||null,source:x.source||null,emotion:x.emotion})), null, 1));
await p.$disconnect();
