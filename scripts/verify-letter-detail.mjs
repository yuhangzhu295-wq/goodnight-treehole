// Letter detail: reads like a letter, the source-record row lands on the record it came from, and the
// favourite toggle is a real server write that survives a reload.
import { withSession } from './device-session.mjs';
import { ensureReverse, navigateTo, typeInto } from './input-helpers.mjs';
import { requireStack, requireStackAtEnd } from './preflight-api.mjs';
await requireStack();
ensureReverse();
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const results = [];
const record = (n, v, note) => { results.push(v); console.log(`${v === 'PASS' ? 'PASS ' : 'FAIL '} ${n}${note ? ' — ' + note : ''}`); };

const readDetail = (ev) => ev(`(function(){
  var t = function(id){var e=document.querySelector('[data-testid='+id+']');return e?(e.innerText||'').trim():null;};
  return JSON.stringify({
    path: location.pathname,
    id: new URLSearchParams(location.search).get('id'),
    meta: t('letter-detail-meta'),
    title: t('letter-detail-title'),
    bodyLen: (t('letter-detail-body')||'').length,
    hasSource: !!document.querySelector('[data-testid=letter-detail-source]'),
    favLabel: (function(){
      var b=document.querySelector('[data-testid=btn-letter-detail-fav]');
      return b ? (b.innerText||'').replace(/\\s+/g,'') : null;
    })(),
    status: t('letter-detail-status'),
    error: (document.querySelector('.load-error')||{}).innerText || null
  });
})()`, false);

await withSession(async (session) => {
  const { ev } = session;

  // 1. open a real letter from the list. A freshly installed app has no letters, and an empty list
  //    cannot show whether a letter opens, so write one mood through the real composer first - the
  //    companion letter is generated by the API for it.
  await navigateTo(session, '/pages/mood/create', { ready: '[data-testid=input-mood-content]' });
  const seeded = await typeInto(session, 'input-mood-content', `回信验证_${Date.now()}`);
  if (seeded.ok) {
    await ev("(function(){document.querySelector('[data-testid=btn-submit-mood]').click();return 1;})()", false);
    await sleep(5000);
  }
  const listed = await navigateTo(session, '/pages/letter/list', { ready: '[data-testid^=letter-card]' });
  const opened = await ev("(function(){var c=document.querySelector('[data-testid^=letter-card]');if(!c)return 0;c.click();return 1;})()", false);
  await sleep(3500);
  const detail = JSON.parse(await readDetail(ev) || '{}');
  const metaOk = /^晚安树洞 · \d{4}年\d{1,2}月\d{1,2}日 \d{2}:\d{2}$/.test(String(detail.meta ?? '').trim());
  record('a letter opens with its author, date, title and body',
    listed && Number(opened) === 1 && detail.path === '/pages/letter/detail' && metaOk
      && !!detail.title && detail.bodyLen > 20 && !detail.error ? 'PASS' : 'FAIL',
    JSON.stringify({ listed, opened, path: detail.path, meta: detail.meta, title: detail.title, bodyLen: detail.bodyLen }));

  // 2. the source-record row lands on the record this letter was written for
  if (detail.hasSource) {
    await ev("(function(){document.querySelector('[data-testid=letter-detail-source]').click();return 1;})()", false);
    await sleep(3500);
    const source = JSON.parse(await ev(`(function(){
      return JSON.stringify({
        path: location.pathname,
        id: new URLSearchParams(location.search).get('id'),
        bodyLen: ((document.querySelector('[data-testid=diary-detail-body]')||{}).innerText || '').length,
        notFound: !!document.querySelector('[data-testid=diary-detail-empty]'),
        error: (document.querySelector('.load-error')||{}).innerText || null
      });
    })()`, false) || '{}');
    record('查看原始记录 opens the record the letter came from',
      source.path === '/pages/diary/detail' && !!source.id && source.bodyLen > 0 && source.notFound === false && !source.error ? 'PASS' : 'FAIL',
      JSON.stringify(source));
  } else {
    record('查看原始记录 opens the record the letter came from', 'FAIL', 'the letter has no source record, so the row was not rendered');
  }

  // 3. favourite is a server write: toggle, reload, confirm the label survived, then put it back
  await navigateTo(session, '/pages/letter/index', { ready: '[data-testid=btn-letter-save]' });
  await ev("(function(){var c=document.querySelector('[data-testid^=letter-card]');if(c){c.click();return 1;}return 0;})()", false);
  await sleep(3000);
  if (!(await ev("(function(){return document.querySelector('[data-testid=btn-letter-detail-fav]')?1:0;})()", false))) {
    // The today page may not link straight to the detail; open the list instead.
    await navigateTo(session, '/pages/letter/list', { ready: '[data-testid^=letter-card]' });
    await ev("(function(){var c=document.querySelector('[data-testid^=letter-card]');if(c){c.click();return 1;}return 0;})()", false);
    await sleep(3000);
  }
  const before = JSON.parse(await readDetail(ev) || '{}');
  const startedFavourite = /已收藏/.test(before.favLabel ?? '');
  await ev("(function(){document.querySelector('[data-testid=btn-letter-detail-fav]').click();return 1;})()", false);
  await sleep(2500);
  const afterToggle = JSON.parse(await readDetail(ev) || '{}');
  const letterId = afterToggle.id;
  await navigateTo(session, `/pages/letter/detail?id=${encodeURIComponent(String(letterId))}`, { ready: '[data-testid=btn-letter-detail-fav]' });
  const afterReload = JSON.parse(await readDetail(ev) || '{}');
  const toggled = /已收藏/.test(afterReload.favLabel ?? '') !== startedFavourite;
  record('favouriting writes through the API and survives a reload', toggled ? 'PASS' : 'FAIL',
    JSON.stringify({ startedFavourite, afterToggle: afterToggle.favLabel, afterReload: afterReload.favLabel }));

  // put the letter back the way it was, so repeated runs stay idempotent
  await ev("(function(){document.querySelector('[data-testid=btn-letter-detail-fav]').click();return 1;})()", false);
  await sleep(2000);

  // 4. an id that does not resolve says so and offers a way out
  await navigateTo(session, '/pages/letter/detail?id=letter_does_not_exist', { ready: '[data-testid=btn-letter-detail-goto-list]' });
  const missing = JSON.parse(await ev(`(function(){
    return JSON.stringify({
      title: (document.querySelector('[data-testid=letter-detail-missing]')||{}).innerText || null,
      backToList: !!document.querySelector('[data-testid=btn-letter-detail-goto-list]')
    });
  })()`, false) || '{}');
  record('an unknown letter id explains itself and offers the list',
    String(missing.title ?? '').includes('没有找到') && missing.backToList === true ? 'PASS' : 'FAIL',
    JSON.stringify(missing));

  // 5. no id at all must resolve today's letter, not a demo id that no real viewer owns
  await navigateTo(session, '/pages/letter/detail', { ready: '[data-testid=letter-detail-title]' });
  const noId = JSON.parse(await readDetail(ev) || '{}');
  record('opening the detail without an id shows today’s letter, with its source row',
    noId.bodyLen > 20 && String(noId.title ?? '').includes('没有找到') === false && noId.hasSource === true ? 'PASS' : 'FAIL',
    JSON.stringify({ title: noId.title, bodyLen: noId.bodyLen, meta: noId.meta, hasSource: noId.hasSource }));
});
await requireStackAtEnd();
const failed = results.filter((r) => r === 'FAIL');
console.log(`\n${results.length - failed.length}/${results.length} letter detail cases passed`);
process.exit(failed.length ? 1 : 0);
